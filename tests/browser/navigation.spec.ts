import { test, expect } from "@playwright/test";

test("workspace navigation resets scroll, restores focus, and survives history and reload", async ({ page }) => {
  await page.goto("/");
  await expect(page.getByRole("heading", { name: "Connect your business with personal AI.", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Assistant", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Your personal assistant", exact: true })).toBeFocused();
  await expect(page.locator(".results-grid .stay-card")).toHaveCount(3);
  await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight));
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBeGreaterThan(0);
  await page.getByRole("button", { name: "Bookings", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Bookings", exact: true })).toBeFocused();
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(0);
  await page.goBack();
  await expect(page.getByRole("heading", { name: "Your personal assistant", exact: true })).toBeFocused();
  await page.goForward();
  await expect(page.getByRole("heading", { name: "Bookings", exact: true })).toBeFocused();
  await page.reload();
  await expect(page.getByRole("heading", { name: "Bookings", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Home", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Connect your business with personal AI.", exact: true })).toBeFocused();
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(0);
  await expect(page.getByRole("button", { name: "Manage listings", exact: true })).toBeVisible();
});

test("simple home connects Agent Hub, accommodation publication, assistant, and workspace menu", async ({ page }) => {
  await page.goto("/");
  await expect(page.getByRole("heading", { name: "Connect your business with personal AI.", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Open Agent Hub", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Agent Hub", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Add agent or skill", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Home", exact: true }).click();
  await page.getByRole("button", { name: "Ask your assistant", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Your personal assistant", exact: true })).toBeFocused();
  await expect(page.getByText("Accommodation · Test booking workflow", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Home", exact: true }).click();
  await page.getByRole("button", { name: "Manage listings", exact: true }).click();
  await page.getByRole("button", { name: "Add listing", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog.getByLabel("Listing name", { exact: true })).toBeVisible();
  await expect(dialog.getByRole("button", { name: "Publish to AgentBridge", exact: true })).toBeVisible();
  await dialog.getByRole("button", { name: "Close dialog", exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole("button", { name: "Add listing", exact: true })).toBeFocused();
  await expect(page.getByRole("heading", { name: "Business listings", exact: true })).toBeVisible();
  await expect(page.locator(".host-list")).toContainText("The Pacific House");
  const more = page.getByRole("button", { name: "More", exact: true });
  await more.click();
  const menu = page.getByRole("dialog", { name: "Workspace menu", exact: true });
  await expect(menu).toBeVisible();
  await menu.getByRole("button", { name: "Close menu", exact: true }).click();
  await expect(menu).not.toBeVisible();
  await expect(more).toBeFocused();
  await more.click();
  await menu.getByRole("button", { name: "Network vision", exact: true }).click();
  await expect(menu).not.toBeVisible();
  await expect(page.locator(".vision-page h1")).toBeFocused();
  await page.getByRole("button", { name: "Home", exact: true }).click();
  await page.getByRole("button", { name: "View bookings", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Bookings", exact: true })).toBeFocused();
  await page.getByRole("button", { name: "Assistant", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Your personal assistant", exact: true })).toBeFocused();
  await expect(page.locator(".assistant-panel")).toBeVisible();
});
